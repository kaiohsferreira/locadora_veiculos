using AutoVia.Core.Entities.PgSql;
using AutoVia.Integrations.Entities;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Conventions;

namespace AutoVia.Infrastructure.Persistence
{
    /// <summary>
    /// Contexto unico do banco da AutoVia: as 14 tabelas de negocio (Apendice A)
    /// e as 2 tabelas da biblioteca de integracoes (Apendice B).
    ///
    /// O esquema nasce daqui (code-first). Cada entidade tem a sua classe
    /// IEntityTypeConfiguration em Persistence/Configurations, aplicada por
    /// ApplyConfigurationsFromAssembly.
    /// </summary>
    public class AutoViaDbContext : DbContext
    {
        public AutoViaDbContext(DbContextOptions<AutoViaDbContext> options)
            : base(options)
        {
        }

        // --- Cadastros basicos ---
        public DbSet<Cliente> Clientes { get; set; } = null!;
        public DbSet<Funcionario> Funcionarios { get; set; } = null!;
        public DbSet<Categoria> Categorias { get; set; } = null!;

        // --- Frota ---
        public DbSet<Veiculo> Veiculos { get; set; } = null!;

        // --- Reserva e locacao ---
        public DbSet<Reserva> Reservas { get; set; } = null!;
        public DbSet<Locacao> Locacoes { get; set; } = null!;
        public DbSet<Vistoria> Vistorias { get; set; } = null!;
        public DbSet<Avaria> Avarias { get; set; } = null!;
        public DbSet<CobrancaExtra> CobrancasExtras { get; set; } = null!;

        // --- Venda e pagamentos ---
        public DbSet<Venda> Vendas { get; set; } = null!;
        public DbSet<Pagamento> Pagamentos { get; set; } = null!;

        // --- Manutencao, seguros e sinistros ---
        public DbSet<Manutencao> Manutencoes { get; set; } = null!;
        public DbSet<Seguro> Seguros { get; set; } = null!;
        public DbSet<Sinistro> Sinistros { get; set; } = null!;

        // --- Biblioteca de integracoes ---
        public DbSet<Integration> Integrations { get; set; } = null!;
        public DbSet<IntegrationSetting> IntegrationSettings { get; set; } = null!;

        protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
        {
            // Por convencao o EF cria um indice para TODA chave estrangeira
            // (IX_reserva_id_veiculo, IX_vistoria_id_funcionario...). A
            // especificacao define exatamente quais indices existem, entao a
            // convencao sai e cada indice e declarado na configuracao da entidade.
            configurationBuilder.Conventions.Remove(typeof(ForeignKeyIndexConvention));
        }

        protected override void OnModelCreating(ModelBuilder modelBuilder)
        {
            base.OnModelCreating(modelBuilder);

            // A especificacao usa SERIAL. Sem isto o Npgsql geraria
            // "GENERATED BY DEFAULT AS IDENTITY", que e outro tipo de coluna.
            modelBuilder.UseSerialColumns();

            modelBuilder.ApplyConfigurationsFromAssembly(typeof(AutoViaDbContext).Assembly);
        }
    }
}
